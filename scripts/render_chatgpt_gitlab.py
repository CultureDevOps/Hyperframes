#!/usr/bin/env python3
"""Offline 720p/30fps French preview from the HyperFrames HTML composition.

Renders the composition's animated diagram states as deterministic keyframes,
then uses FFmpeg for frame holds, SRT burn-in, audio mix and H264/AAC mux.
The full video is NOT generated by 'hyperframes render': it is a review render
of the same HTML composition, generated offline with Chromium + ffmpeg.
No upload, no network TTS, no public media artifact.
"""
from __future__ import annotations
import argparse, asyncio, json, math, subprocess, tempfile, wave
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
COMPOSITION=ROOT/'compositions/culturedevops/chatgpt-gitlab'
DATA=json.loads((COMPOSITION/'narration.json').read_text(encoding='utf-8'))
RATE=22050

def command(args):
    subprocess.run([str(x) for x in args],check=True,stdout=subprocess.DEVNULL)

def srt_timestamp(t):
    ms=int(round(t*1000));h,ms=divmod(ms,3600000);m,ms=divmod(ms,60000);s,ms=divmod(ms,1000)
    return f'{h:02}:{m:02}:{s:02},{ms:03}'

def subtitles(items, path):
    lines=[]
    for n,(start,end,text) in enumerate(items,1):
        from textwrap import wrap
        wrapped='\n'.join(wrap(text,width=61,break_long_words=False,break_on_hyphens=False)[:3])
        lines.extend([str(n),f'{srt_timestamp(start)} --> {srt_timestamp(end)}',wrapped,''])
    path.write_text('\n'.join(lines),encoding='utf-8')

def narration(work):
    import array
    all_audio=array.array('h');cues=[];durations=[];cursor=0.;voice_samples=0
    for i,scene in enumerate(DATA['scenes']):
        start=cursor
        for j,phrase in enumerate(scene['lines']):
            p=work/f'voice-{i:02}-{j:02}.wav'
            command(['espeak','-v','fr','-s','156','-a','145','-w',p,phrase])
            with wave.open(str(p),'rb') as w:
                if w.getnchannels()!=1 or w.getsampwidth()!=2 or w.getframerate()!=RATE:
                    raise RuntimeError('Unexpected eSpeak PCM format')
                frames=w.readframes(w.getnframes());n=w.getnframes()
            samples=array.array('h');samples.frombytes(frames)
            if __import__('sys').byteorder!='little':samples.byteswap()
            begin=cursor;all_audio.extend(samples);cursor+=n/RATE
            cues.append((begin,cursor,phrase));voice_samples+=n
            pause=0.32 if j<len(scene['lines'])-1 else 1.8
            all_audio.extend([0]*round(pause*RATE));cursor+=round(pause*RATE)/RATE
        durations.append(cursor-start)
    voice=work/'narration.wav'
    with wave.open(str(voice),'wb') as w:
        w.setnchannels(1);w.setsampwidth(2);w.setframerate(RATE);w.writeframes(all_audio.tobytes())
    return voice,cues,durations,cursor

async def images(work):
    from playwright.async_api import async_playwright
    html=(COMPOSITION/'index.html').read_text(encoding='utf-8')
    async with async_playwright() as p:
        browser=await p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage','--disable-gpu'])
        try:
            page=await browser.new_page(viewport={'width':1280,'height':720},device_scale_factor=1)
            await page.set_content(html,wait_until='load')
            await page.add_style_tag(content='*,*:before,*:after{animation:none!important;transition:none!important}')
            for i in range(len(DATA['scenes'])):
                for step in range(3):
                    await page.evaluate('([data,i,k])=>window.renderFrame(data,i,k)',[DATA,i,step])
                    await page.screenshot(path=str(work/f'shot-{i:02}-{step}.png'),type='png')
        finally:await browser.close()

def soundtrack(work,duration):
    # Original deterministic slow ambient pulse. Voice remains above background.
    import array
    n=round(duration*RATE); out=array.array('h'); chords=[(110,165,220),(98,147,196),(130.8,196,261.6),(116.5,174.6,233)]
    for j in range(n):
        t=j/RATE; chord=chords[int(t//12)%4]; amp=0.13*(0.35+0.65*min(1,t/6, (duration-t)/6))
        v=sum(math.sin(2*math.pi*f*t) for f in chord)/3
        # soften attacks and never compete with voice
        out.append(int(max(-1,min(1,amp*v))*32767))
    path=work/'original-music.wav'
    with wave.open(str(path),'wb') as w:w.setnchannels(1);w.setsampwidth(2);w.setframerate(RATE);w.writeframes(out.tobytes())
    return path

def concat_file(work,durations):
    content=[]
    for i,total in enumerate(durations):
        for k in range(3):
            content.append(f"file '{(work/f'shot-{i:02}-{k}.png').as_posix()}'")
            content.append(f'duration {total/3:.6f}')
    content.append(f"file '{(work/f'shot-{len(durations)-1:02}-2.png').as_posix()}'")
    f=work/'slideshow.ffconcat';f.write_text('\n'.join(content)+'\n',encoding='utf-8');return f

def main():
    p=argparse.ArgumentParser();p.add_argument('--output',type=Path,required=True);p.add_argument('--only-assets',action='store_true');p.add_argument('--work',type=Path);args=p.parse_args()
    args.output=args.output.resolve();args.output.parent.mkdir(parents=True,exist_ok=True)
    if args.output.is_relative_to(ROOT):
        raise SystemExit('Refusing MP4 inside public Git checkout')
    with tempfile.TemporaryDirectory(prefix='ops010-local-') if args.work is None else __import__('contextlib').nullcontext(str(args.work)) as folder:
        work=Path(folder);work.mkdir(parents=True,exist_ok=True)
        voice,cues,durations,duration=narration(work)
        srt=args.output.with_suffix('.srt');subtitles(cues,srt)
        print(f'VOICE_DURATION={duration:.3f} secs; chapters={list(round(x,1) for x in durations)}',flush=True)
        if not 300<=duration<=420:raise RuntimeError('Narration out of expected 5–7 minute range')
        asyncio.run(images(work))
        if args.only_assets:return
        music=soundtrack(work,duration);concat=concat_file(work,durations)
        fontstyle="FontName=DejaVu Sans,FontSize=21,PrimaryColour=&HFFFFFF,OutlineColour=&H070B19,BorderStyle=1,Outline=2,Shadow=0,Alignment=2,MarginV=28"
        # SRT is generated only from our own plain-text narration; no external MP4 parsing.
        subpath=str(srt).replace('\\','/').replace(':','\\:').replace("'","\\'")
        vf=f"fps=30,scale=1280:720:flags=lanczos,format=yuv420p,subtitles='{subpath}':force_style='{fontstyle}'"
        # Two passes avoid buffering the entire 7-minute audio stream while the
        # slower still-image video timestamps advance (OOM on small runners).
        video_only=work/'picture-only.mp4'
        command(['ffmpeg','-hide_banner','-loglevel','error','-y','-threads','1','-filter_threads','1',
            '-safe','0','-f','concat','-i',concat,'-t',f'{duration:.3f}',
            '-vf',vf,'-c:v','libx264','-threads','1','-preset','ultrafast',
            '-crf','25','-r','30','-pix_fmt','yuv420p',video_only])
        audio_only=work/'mix.wav'
        command(['ffmpeg','-hide_banner','-loglevel','error','-y','-i',voice,'-i',music,
            '-filter_complex','[0:a]volume=1.6[voice];[1:a]volume=0.12[music];'
            '[voice][music]amix=inputs=2:duration=first:dropout_transition=0,alimiter=limit=0.88[a]',
            '-map','[a]','-c:a','pcm_s16le',audio_only])
        command(['ffmpeg','-hide_banner','-loglevel','error','-y','-i',video_only,'-i',audio_only,
            '-map','0:v:0','-map','1:a:0','-c:v','copy','-c:a','aac','-b:a','160k',
            '-t',f'{duration:.3f}','-movflags','+faststart',args.output])
        probe=subprocess.run(['ffprobe','-v','error','-show_format','-show_streams','-of','json',args.output],check=True,capture_output=True,text=True)
        metadata=json.loads(probe.stdout);v=next(s for s in metadata['streams'] if s['codec_type']=='video');a=next(s for s in metadata['streams'] if s['codec_type']=='audio');duration_actual=float(metadata['format']['duration'])
        assert (v['width'],v['height'],v['avg_frame_rate'],v['codec_name'])==(1280,720,'30/1','h264'),v
        assert a['codec_name']=='aac' and abs(duration_actual-duration)<0.45,(a,duration_actual,duration)
        print(f'RENDER_VERIFIED path={args.output} duration={duration_actual:.3f} size={args.output.stat().st_size} 1280x720 30fps H264/AAC',flush=True)

if __name__=='__main__':main()